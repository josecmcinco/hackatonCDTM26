import re
from enum import Enum

def crear_enum_desde_dict(nombre_enum: str, diccionario: dict) -> Enum:
    """Genera dinámicamente un Enum a partir de cualquier diccionario clave-valor."""
    miembros = {}
    for k, v in diccionario.items():
        s = str(k).strip()
        s = s.replace("á", "a").replace("é", "e").replace("í", "i").replace("ó", "o").replace("ú", "u")
        s = s.replace("ñ", "n").replace("Ñ", "N")
        ident = re.sub(r"[^a-zA-Z0-9_]", "_", s).strip("_").upper()
        if not ident or ident[0].isdigit():
            ident = f"VAL_{ident}"
        miembros[ident] = k
    return Enum(nombre_enum, miembros)

